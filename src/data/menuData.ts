const FALLBACK_IMAGE = "/images/placeholders/bbq-placeholder.jpg";

const resolveImageFromKey = (imageKey: string) => {
  const registrySlug = IMAGE_KEY_TO_REGISTRY_SLUG[imageKey];
  if (!registrySlug) {
    return { imageUrl: FALLBACK_IMAGE, detailImageUrl: FALLBACK_IMAGE };
  }

  const entry = menuImageRegistry[registrySlug];
  if (!entry) {
    return { imageUrl: FALLBACK_IMAGE, detailImageUrl: FALLBACK_IMAGE };
  }

  return {
    imageUrl: entry.primaryImage || FALLBACK_IMAGE,
    detailImageUrl: entry.detailImage || entry.primaryImage || FALLBACK_IMAGE,
  };
};

const buildMenuItem = (item: Omit<MenuItem, "imageUrl" | "detailImageUrl">): MenuItem => {
  const { imageUrl, detailImageUrl } = resolveImageFromKey(item.imageKey);
  return {
    ...item,
    imageUrl,
    detailImageUrl,
  };
};

